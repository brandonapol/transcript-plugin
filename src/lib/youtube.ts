import type { Chapter, Cue } from "./cues.ts";
import { parseTranscript } from "./cues.ts";

export type YoutubeTape = {
  videoId: string;
  title: string;
  author: string;
  duration: number;
  cues: Cue[];
  chapters: Chapter[];
};

const INSTANCES = ["https://api.piped.private.coffee"];

export class CaptionError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "CaptionError";
  }
}

type Subtitle = {
  url?: string;
  code?: string;
  autoGenerated?: boolean;
};

function pickSubtitle(list: Subtitle[]): Subtitle | null {
  const usable = list.filter((item) => typeof item.url === "string");
  return (
    usable.find((item) => item.code?.startsWith("en") && !item.autoGenerated) ??
    usable.find((item) => item.code?.startsWith("en")) ??
    usable[0] ??
    null
  );
}

function readChapters(raw: unknown): Chapter[] {
  if (!Array.isArray(raw)) return [];
  const chapters: Chapter[] = [];
  for (const item of raw) {
    if (!item || typeof item !== "object") continue;
    const record = item as Record<string, unknown>;
    const title = typeof record.title === "string" ? record.title.trim() : "";
    const start = Number(record.start ?? record.startTime ?? record.time);
    if (!title || !Number.isFinite(start)) continue;
    chapters.push({ start, title: title.slice(0, 140) });
    if (chapters.length >= 40) break;
  }
  return chapters;
}

async function fetchText(url: string): Promise<string> {
  const response = await fetch(url, {
    headers: { accept: "application/json, text/xml, */*" },
    signal: AbortSignal.timeout(14_000),
  });
  if (!response.ok) {
    throw new CaptionError(`Caption host answered ${response.status}`);
  }
  return response.text();
}

export async function fetchYoutubeTape(videoId: string): Promise<YoutubeTape> {
  let lastError = "Couldn't read captions for that video.";
  for (const base of INSTANCES) {
    try {
      const payload = JSON.parse(
        await fetchText(`${base}/streams/${videoId}`),
      ) as Record<string, unknown>;
      const title =
        typeof payload.title === "string" && payload.title.trim()
          ? payload.title.trim()
          : "Untitled video";
      const author =
        typeof payload.uploader === "string" ? payload.uploader.trim() : "";
      const duration = Number(payload.duration);
      const subtitles = Array.isArray(payload.subtitles)
        ? (payload.subtitles as Subtitle[])
        : [];
      const track = pickSubtitle(subtitles);
      if (!track?.url) {
        lastError =
          "That video has no captions. Paste an SRT, VTT, or timestamped transcript.";
        continue;
      }
      const body = await fetchText(track.url);
      const parsed = parseTranscript(body);
      if (!parsed.cues.length) {
        lastError =
          "The captions came back empty. Paste the transcript and pull again.";
        continue;
      }
      const end = parsed.cues[parsed.cues.length - 1]?.end ?? 0;
      return {
        videoId,
        title,
        author,
        duration: Number.isFinite(duration) && duration > 0 ? duration : end,
        cues: parsed.cues,
        chapters: readChapters(payload.chapters),
      };
    } catch (error) {
      lastError =
        error instanceof CaptionError
          ? error.message
          : "Couldn't reach a caption host for that video. Paste the transcript instead.";
    }
  }
  throw new CaptionError(lastError);
}
